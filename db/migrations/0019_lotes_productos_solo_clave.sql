-- Migración 0019. LOTES_PRODUCTOS identifica productos externos solo por CLAVE_PRODUCTO.
-- El ID de la fila sigue siendo identity. Se elimina ID_PRODUCTO.

UPDATE "LOTES_PRODUCTOS"
SET "CLAVE_PRODUCTO" = COALESCE(
  NULLIF(btrim("CLAVE_PRODUCTO"), ''),
  CASE
    WHEN "ID_PRODUCTO" IS NOT NULL THEN "ID_PRODUCTO"::text
    ELSE NULL
  END
)
WHERE "CLAVE_PRODUCTO" IS NULL
   OR btrim("CLAVE_PRODUCTO") = '';

DELETE FROM "LOTES_PRODUCTOS"
WHERE "CLAVE_PRODUCTO" IS NULL
   OR btrim("CLAVE_PRODUCTO") = '';

ALTER TABLE "LOTES_PRODUCTOS"
  DROP CONSTRAINT "LOTES_PRODUCTOS_REFERENCIA_CHK",
  DROP CONSTRAINT "LOTES_PRODUCTOS_ID_PRODUCTO_CHK",
  DROP CONSTRAINT "LOTES_PRODUCTOS_CLAVE_PRODUCTO_CHK";

ALTER TABLE "LOTES_PRODUCTOS"
  DROP COLUMN "ID_PRODUCTO";

ALTER TABLE "LOTES_PRODUCTOS"
  ALTER COLUMN "CLAVE_PRODUCTO" SET NOT NULL;

ALTER TABLE "LOTES_PRODUCTOS"
  ADD CONSTRAINT "LOTES_PRODUCTOS_CLAVE_PRODUCTO_CHK" CHECK (
    length(btrim("CLAVE_PRODUCTO")) > 0
  );
