-- Migración 0024. UBICACION_SALIDA_ID reemplaza CLAVE_UBICACION_SALIDA.
-- La clave se resuelve contra UBICACIONES.CODIGO con btrim, sensible a mayúsculas.
-- Si una clave no nula no tiene CODIGO, la migración aborta y conserva la columna.
-- RECEPCIONES une una expedición con la ubicación donde se recibe.
-- No editar este archivo. El siguiente cambio va en una migración nueva
-- y debe reflejarse en db/init.sql.

BEGIN;

ALTER TABLE "EXPEDICIONES"
  ADD COLUMN "UBICACION_SALIDA_ID" integer;

UPDATE "EXPEDICIONES" AS expedicion
SET "UBICACION_SALIDA_ID" = ubicacion."ID"
FROM "UBICACIONES" AS ubicacion
WHERE expedicion."CLAVE_UBICACION_SALIDA" IS NOT NULL
  AND ubicacion."CODIGO" = btrim(expedicion."CLAVE_UBICACION_SALIDA");

DO $$
DECLARE
  pendientes text;
BEGIN
  SELECT string_agg(clave, ', ' ORDER BY clave)
  INTO pendientes
  FROM (
    SELECT DISTINCT btrim("CLAVE_UBICACION_SALIDA") AS clave
    FROM "EXPEDICIONES"
    WHERE "CLAVE_UBICACION_SALIDA" IS NOT NULL
      AND "UBICACION_SALIDA_ID" IS NULL
  ) AS faltantes;

  IF pendientes IS NOT NULL THEN
    RAISE EXCEPTION 'CLAVE_UBICACION_SALIDA sin ubicacion: %', pendientes
      USING ERRCODE = '23503';
  END IF;
END $$;

ALTER TABLE "EXPEDICIONES"
  DROP CONSTRAINT "EXPEDICIONES_CLAVE_UBICACION_SALIDA_CHK",
  DROP COLUMN "CLAVE_UBICACION_SALIDA";

ALTER TABLE "EXPEDICIONES"
  ADD CONSTRAINT "EXPEDICIONES_UBICACION_SALIDA_ID_FK"
    FOREIGN KEY ("UBICACION_SALIDA_ID") REFERENCES "UBICACIONES" ("ID");

CREATE INDEX "EXPEDICIONES_UBICACION_SALIDA_ID_IDX"
  ON "EXPEDICIONES" ("UBICACION_SALIDA_ID");

CREATE TABLE "RECEPCIONES" (
  "ID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ID_EXPEDICION" integer NOT NULL,
  "UBICACION_ID" integer NOT NULL,
  "USUARIO_ID" integer,
  "ID_ORIGEN_USUARIO" integer,
  "CREADO_EN" timestamptz NOT NULL DEFAULT now(),
  "ACTUALIZADO_EN" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "RECEPCIONES_ID_EXPEDICION_FK"
    FOREIGN KEY ("ID_EXPEDICION") REFERENCES "EXPEDICIONES" ("ID"),
  CONSTRAINT "RECEPCIONES_UBICACION_ID_FK"
    FOREIGN KEY ("UBICACION_ID") REFERENCES "UBICACIONES" ("ID"),
  CONSTRAINT "RECEPCIONES_ID_ORIGEN_USUARIO_FK"
    FOREIGN KEY ("ID_ORIGEN_USUARIO") REFERENCES "USUARIOS_ORIGENES" ("ID"),
  CONSTRAINT "RECEPCIONES_USUARIO_ID_CHK" CHECK ("USUARIO_ID" > 0),
  CONSTRAINT "RECEPCIONES_USUARIO_ORIGEN_CHK" CHECK (
    ("USUARIO_ID" IS NULL) = ("ID_ORIGEN_USUARIO" IS NULL)
  )
);

CREATE INDEX "RECEPCIONES_ID_EXPEDICION_IDX"
  ON "RECEPCIONES" ("ID_EXPEDICION");

CREATE INDEX "RECEPCIONES_UBICACION_ID_IDX"
  ON "RECEPCIONES" ("UBICACION_ID");

CREATE INDEX "RECEPCIONES_ID_ORIGEN_USUARIO_IDX"
  ON "RECEPCIONES" ("ID_ORIGEN_USUARIO");

CREATE TRIGGER "RECEPCIONES_ACTUALIZADO_TRG"
  BEFORE UPDATE ON "RECEPCIONES"
  FOR EACH ROW
  EXECUTE FUNCTION marcar_actualizado_en();

CREATE TRIGGER "RECEPCIONES_USUARIO_REF_TRG"
  BEFORE INSERT OR UPDATE ON "RECEPCIONES"
  FOR EACH ROW
  EXECUTE FUNCTION usuario_referencia_validar();

ALTER TABLE "RECEPCIONES" OWNER TO packing;

COMMIT;
