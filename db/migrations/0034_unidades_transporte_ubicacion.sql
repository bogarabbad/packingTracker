-- Migración 0034. UBICACION_ID en UNIDADES_TRANSPORTE (ubicación actual)
-- y UNIDADES_TRANSPORTE_UBICACIONES como historial N:N con FECHA.
-- El registro de historial más reciente (FECHA, ID) define la ubicación actual.
-- No editar este archivo. El siguiente cambio va en una migración nueva
-- y debe reflejarse en db/init.sql.

BEGIN;

ALTER TABLE "UNIDADES_TRANSPORTE"
  ADD COLUMN "UBICACION_ID" integer;

ALTER TABLE "UNIDADES_TRANSPORTE"
  ADD CONSTRAINT "UNIDADES_TRANSPORTE_UBICACION_ID_FK"
    FOREIGN KEY ("UBICACION_ID") REFERENCES "UBICACIONES" ("ID");

CREATE INDEX "UNIDADES_TRANSPORTE_UBICACION_ID_IDX"
  ON "UNIDADES_TRANSPORTE" ("UBICACION_ID");

CREATE TABLE "UNIDADES_TRANSPORTE_UBICACIONES" (
  "ID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ID_UNIDAD" integer NOT NULL,
  "UBICACION_ID" integer NOT NULL,
  "FECHA" timestamptz NOT NULL DEFAULT now(),
  "ES_SEMILLA" boolean NOT NULL DEFAULT false,
  "CREADO_EN" timestamptz NOT NULL DEFAULT now(),
  "ACTUALIZADO_EN" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "UNIDADES_TRANSPORTE_UBICACIONES_ID_UNIDAD_FK"
    FOREIGN KEY ("ID_UNIDAD") REFERENCES "UNIDADES_TRANSPORTE" ("ID"),
  CONSTRAINT "UNIDADES_TRANSPORTE_UBICACIONES_UBICACION_ID_FK"
    FOREIGN KEY ("UBICACION_ID") REFERENCES "UBICACIONES" ("ID")
);

CREATE INDEX "UNIDADES_TRANSPORTE_UBICACIONES_ID_UNIDAD_IDX"
  ON "UNIDADES_TRANSPORTE_UBICACIONES" ("ID_UNIDAD");

CREATE INDEX "UNIDADES_TRANSPORTE_UBICACIONES_UBICACION_ID_IDX"
  ON "UNIDADES_TRANSPORTE_UBICACIONES" ("UBICACION_ID");

CREATE INDEX "UNIDADES_TRANSPORTE_UBICACIONES_FECHA_IDX"
  ON "UNIDADES_TRANSPORTE_UBICACIONES" ("FECHA" DESC, "ID" DESC);

CREATE TRIGGER "UNIDADES_TRANSPORTE_UBICACIONES_ACTUALIZADO_TRG"
  BEFORE UPDATE ON "UNIDADES_TRANSPORTE_UBICACIONES"
  FOR EACH ROW
  EXECUTE FUNCTION marcar_actualizado_en();

CREATE OR REPLACE FUNCTION unidad_transporte_sincronizar_ubicacion(
  p_id_unidad integer
)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
  ubicacion_actual integer;
BEGIN
  SELECT h."UBICACION_ID"
    INTO ubicacion_actual
  FROM "UNIDADES_TRANSPORTE_UBICACIONES" AS h
  WHERE h."ID_UNIDAD" = p_id_unidad
  ORDER BY h."FECHA" DESC, h."ID" DESC
  LIMIT 1;

  UPDATE "UNIDADES_TRANSPORTE"
  SET "UBICACION_ID" = ubicacion_actual
  WHERE "ID" = p_id_unidad;
END;
$$;

ALTER TABLE "UNIDADES_TRANSPORTE_UBICACIONES" OWNER TO packing;
ALTER FUNCTION unidad_transporte_sincronizar_ubicacion(integer) OWNER TO packing;

COMMIT;
