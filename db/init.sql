CREATE OR REPLACE FUNCTION expediciones_lotes_validar()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  cierre timestamptz;
  creada timestamptz;
  cierre_anterior timestamptz;
  padre_id integer;
BEGIN
  IF TG_OP = 'DELETE' THEN
    SELECT "FECHA_CIERRE" INTO cierre
    FROM "EXPEDICIONES"
    WHERE "ID" = OLD."ID_EXPEDICION";

    IF cierre IS NOT NULL THEN
      RAISE EXCEPTION 'la expedicion cerrada conserva sus lotes' USING ERRCODE = '23514';
    END IF;

    RETURN OLD;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    SELECT "FECHA_CIERRE" INTO cierre_anterior
    FROM "EXPEDICIONES"
    WHERE "ID" = OLD."ID_EXPEDICION";

    IF cierre_anterior IS NOT NULL THEN
      RAISE EXCEPTION 'la expedicion cerrada conserva sus lotes' USING ERRCODE = '23514';
    END IF;
  END IF;

  SELECT "FECHA_CIERRE", "CREADO_EN" INTO cierre, creada
  FROM "EXPEDICIONES"
  WHERE "ID" = NEW."ID_EXPEDICION";

  IF creada IS NULL THEN
    RAISE EXCEPTION 'expedicion inexistente' USING ERRCODE = '23503';
  END IF;

  IF cierre IS NOT NULL THEN
    RAISE EXCEPTION 'no se embarcan lotes en una expedicion cerrada' USING ERRCODE = '23514';
  END IF;

  IF NEW."EMBARCADO_EN" < creada THEN
    RAISE EXCEPTION 'el embarque no puede ser anterior a la expedicion' USING ERRCODE = '23514';
  END IF;

  SELECT "PADRE_ID" INTO padre_id
  FROM "LOTES"
  WHERE "ID" = NEW."ID_LOTE";

  IF NOT FOUND THEN
    RAISE EXCEPTION 'lote inexistente' USING ERRCODE = '23503';
  END IF;

  IF padre_id IS NOT NULL THEN
    RAISE EXCEPTION 'solo se embarcan lotes sin padre' USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER "EXPEDICIONES_LOTES_TRG"
  BEFORE INSERT OR UPDATE OR DELETE ON "EXPEDICIONES_LOTES"
  FOR EACH ROW
  EXECUTE FUNCTION expediciones_lotes_validar();

CREATE OR REPLACE FUNCTION recepciones_lotes_validar()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  ubicacion_recepcion integer;
  padre_id integer;
  destino_id integer;
BEGIN
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  SELECT "UBICACION_ID" INTO ubicacion_recepcion
  FROM "RECEPCIONES"
  WHERE "ID" = NEW."ID_RECEPCION";

  IF NOT FOUND THEN
    RAISE EXCEPTION 'recepcion inexistente' USING ERRCODE = '23503';
  END IF;

  SELECT "PADRE_ID" INTO padre_id
  FROM "LOTES"
  WHERE "ID" = NEW."ID_LOTE";

  IF NOT FOUND THEN
    RAISE EXCEPTION 'lote inexistente' USING ERRCODE = '23503';
  END IF;

  IF padre_id IS NOT NULL THEN
    RAISE EXCEPTION 'solo se reciben lotes sin padre' USING ERRCODE = '23514';
  END IF;

  SELECT relacion."UBICACION_ID" INTO destino_id
  FROM "LOTES_UBICACIONES" AS relacion
  JOIN "LOTES_UBICACIONES_TIPOS" AS tipo ON tipo."ID" = relacion."ID_TIPO"
  WHERE relacion."ID_LOTE" = NEW."ID_LOTE"
    AND tipo."CODIGO" = 'DESTINO';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'el lote no tiene destino' USING ERRCODE = '23514';
  END IF;

  IF destino_id IS DISTINCT FROM ubicacion_recepcion THEN
    RAISE EXCEPTION 'el destino del lote no coincide con la recepcion'
      USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER "RECEPCIONES_LOTES_TRG"
  BEFORE INSERT OR UPDATE OR DELETE ON "RECEPCIONES_LOTES"
  FOR EACH ROW
  EXECUTE FUNCTION recepciones_lotes_validar();

CREATE OR REPLACE FUNCTION lotes_validar()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  tipo_final boolean;
  padre_final boolean;
BEGIN
  SELECT "ES_FINAL" INTO tipo_final
  FROM "LOTES_TIPOS"
  WHERE "ID" = NEW."ID_TIPO";

  IF tipo_final IS NULL THEN
    RAISE EXCEPTION 'tipo de lote inexistente' USING ERRCODE = '23503';
  END IF;

  IF tipo_final THEN
    IF NEW."ID_UNIDAD" IS NOT NULL THEN
      RAISE EXCEPTION 'un lote final no se embarca en la unidad' USING ERRCODE = '23514';
    END IF;

    IF NEW."PADRE_ID" IS NOT NULL THEN
      IF EXISTS (
        SELECT 1
        FROM "EXPEDICIONES_LOTES"
        WHERE "ID_LOTE" = NEW."ID"
      ) THEN
        RAISE EXCEPTION 'un lote embarcado no puede tener padre' USING ERRCODE = '23514';
      END IF;

      IF EXISTS (
        SELECT 1
        FROM "RECEPCIONES_LOTES"
        WHERE "ID_LOTE" = NEW."ID"
      ) THEN
        RAISE EXCEPTION 'un lote recibido no puede tener padre' USING ERRCODE = '23514';
      END IF;

      SELECT tipo."ES_FINAL" INTO padre_final
      FROM "LOTES" AS padre
      JOIN "LOTES_TIPOS" AS tipo ON tipo."ID" = padre."ID_TIPO"
      WHERE padre."ID" = NEW."PADRE_ID";

      IF padre_final IS NULL THEN
        RAISE EXCEPTION 'lote padre inexistente' USING ERRCODE = '23503';
      END IF;

      IF padre_final THEN
        RAISE EXCEPTION 'una categoria final no contiene lotes' USING ERRCODE = '23514';
      END IF;
    END IF;

    IF TG_OP = 'UPDATE' AND NEW."ID_TIPO" IS DISTINCT FROM OLD."ID_TIPO" THEN
      IF EXISTS (SELECT 1 FROM "LOTES" WHERE "PADRE_ID" = NEW."ID") THEN
        RAISE EXCEPTION 'una categoria final no contiene lotes' USING ERRCODE = '23514';
      END IF;

      IF EXISTS (
        SELECT 1
        FROM "LOTES_PRODUCTOS" AS producto
        WHERE producto."ID_LOTE" = NEW."ID"
          AND NOT EXISTS (
            SELECT 1
            FROM "LOTES_TIPOS_UNIDADES" AS relacion
            WHERE relacion."ID_TIPO" = NEW."ID_TIPO"
              AND relacion."ID_UNIDAD" = producto."ID_UNIDAD"
          )
      ) THEN
        RAISE EXCEPTION 'la medida del producto no corresponde al tipo de lote' USING ERRCODE = '23514';
      END IF;
    END IF;
  ELSE
    IF NEW."PADRE_ID" IS NOT NULL THEN
      RAISE EXCEPTION 'solo un lote final puede ir dentro de otro lote' USING ERRCODE = '23514';
    END IF;

    IF EXISTS (SELECT 1 FROM "LOTES_PRODUCTOS" WHERE "ID_LOTE" = NEW."ID") THEN
      RAISE EXCEPTION 'un lote que no es final no contiene productos' USING ERRCODE = '23514';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION lotes_productos_validar()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  es_final boolean;
  entera boolean;
BEGIN
  SELECT tipo."ES_FINAL" INTO es_final
  FROM "LOTES" AS lote
  JOIN "LOTES_TIPOS" AS tipo ON tipo."ID" = lote."ID_TIPO"
  WHERE lote."ID" = NEW."ID_LOTE";

  IF es_final IS NULL THEN
    RAISE EXCEPTION 'lote inexistente' USING ERRCODE = '23503';
  END IF;

  IF NOT es_final THEN
    RAISE EXCEPTION 'solo un lote final contiene productos' USING ERRCODE = '23514';
  END IF;

  SELECT "ENTERA" INTO entera
  FROM "UNIDADES"
  WHERE "ID" = NEW."ID_UNIDAD";

  IF entera IS NULL THEN
    RAISE EXCEPTION 'unidad inexistente' USING ERRCODE = '23503';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM "LOTES" AS lote
    JOIN "LOTES_TIPOS_UNIDADES" AS relacion ON relacion."ID_TIPO" = lote."ID_TIPO"
    WHERE lote."ID" = NEW."ID_LOTE"
      AND relacion."ID_UNIDAD" = NEW."ID_UNIDAD"
  ) THEN
    RAISE EXCEPTION 'la medida del producto no corresponde al tipo de lote' USING ERRCODE = '23514';
  END IF;

  IF entera AND NEW."CANTIDAD" <> trunc(NEW."CANTIDAD") THEN
    RAISE EXCEPTION 'la cantidad de esta unidad debe ser entera' USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION lotes_tipos_validar()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NOT NEW."ES_FINAL" AND EXISTS (
    SELECT 1
    FROM "LOTES" AS lote
    JOIN "LOTES_PRODUCTOS" AS producto ON producto."ID_LOTE" = lote."ID"
    WHERE lote."ID_TIPO" = NEW."ID"
  ) THEN
    RAISE EXCEPTION 'el tipo tiene productos y debe seguir siendo final' USING ERRCODE = '23514';
  END IF;

  IF NEW."ES_FINAL" AND EXISTS (
    SELECT 1
    FROM "LOTES" AS hijo
    JOIN "LOTES" AS padre ON padre."ID" = hijo."PADRE_ID"
    WHERE padre."ID_TIPO" = NEW."ID"
  ) THEN
    RAISE EXCEPTION 'el tipo contiene lotes y no puede ser final' USING ERRCODE = '23514';
  END IF;

  IF NOT NEW."ES_FINAL" AND EXISTS (
    SELECT 1 FROM "LOTES"
    WHERE "ID_TIPO" = NEW."ID" AND "PADRE_ID" IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'un tipo no final no puede estar dentro de otro lote' USING ERRCODE = '23514';
  END IF;

  IF NOT NEW."ES_FINAL" AND EXISTS (
    SELECT 1 FROM "LOTES_TIPOS_UNIDADES" WHERE "ID_TIPO" = NEW."ID"
  ) THEN
    RAISE EXCEPTION 'un tipo que no es final no mide producto' USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION unidades_validar()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW."ENTERA" AND EXISTS (
    SELECT 1
    FROM "LOTES_PRODUCTOS"
    WHERE "ID_UNIDAD" = NEW."ID"
      AND "CANTIDAD" <> trunc("CANTIDAD")
  ) THEN
    RAISE EXCEPTION 'hay cantidades fraccionarias para esta unidad' USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

