CREATE OR REPLACE FUNCTION usuario_referencia_validar()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF (NEW."USUARIO_ID" IS NULL) <> (NEW."ID_ORIGEN_USUARIO" IS NULL) THEN
    RAISE EXCEPTION 'usuario y origen deben ir juntos' USING ERRCODE = '23514';
  END IF;

  IF NEW."USUARIO_ID" IS NULL THEN
    RETURN NEW;
  END IF;

  IF NEW."ID_ORIGEN_USUARIO" = 1
     AND NOT EXISTS (
       SELECT 1 FROM "USUARIOS" WHERE "ID" = NEW."USUARIO_ID"
     ) THEN
    RAISE EXCEPTION 'usuario interno inexistente' USING ERRCODE = '23503';
  END IF;

  RETURN NEW;
END;
$$;

