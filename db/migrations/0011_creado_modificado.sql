-- Migración 0011. Cada registro guarda cuándo se creó y cuándo se modificó.
-- CREADO_EN queda fijo. ACTUALIZADO_EN se mueve en cada UPDATE.
-- Los registros que ya existían reciben la fecha de esta migración.
-- No editar este archivo. El siguiente cambio va en una migración nueva
-- y debe reflejarse en db/init.sql.

BEGIN;

ALTER TABLE "UNIDADES_ESTATUS"
  ADD COLUMN "CREADO_EN" timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN "ACTUALIZADO_EN" timestamptz NOT NULL DEFAULT now();

ALTER TABLE "UNIDADES_TIPOS"
  ADD COLUMN "CREADO_EN" timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN "ACTUALIZADO_EN" timestamptz NOT NULL DEFAULT now();

ALTER TABLE "UNIDADES"
  ADD COLUMN "CREADO_EN" timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN "ACTUALIZADO_EN" timestamptz NOT NULL DEFAULT now();

ALTER TABLE "LOTES_TIPOS"
  ADD COLUMN "CREADO_EN" timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN "ACTUALIZADO_EN" timestamptz NOT NULL DEFAULT now();

ALTER TABLE "LOTES_TIPOS_UNIDADES"
  ADD COLUMN "CREADO_EN" timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN "ACTUALIZADO_EN" timestamptz NOT NULL DEFAULT now();

ALTER TABLE "LOTES"
  ADD COLUMN "CREADO_EN" timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN "ACTUALIZADO_EN" timestamptz NOT NULL DEFAULT now();

ALTER TABLE "LOTES_PRODUCTOS"
  ADD COLUMN "CREADO_EN" timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN "ACTUALIZADO_EN" timestamptz NOT NULL DEFAULT now();

ALTER TABLE "EXPEDICIONES_LOTES"
  ADD COLUMN "CREADO_EN" timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN "ACTUALIZADO_EN" timestamptz NOT NULL DEFAULT now();

CREATE OR REPLACE FUNCTION marcar_actualizado_en()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW."CREADO_EN" := OLD."CREADO_EN";
  NEW."ACTUALIZADO_EN" := now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER "UNIDADES_ESTATUS_ACTUALIZADO_TRG"
  BEFORE UPDATE ON "UNIDADES_ESTATUS"
  FOR EACH ROW
  EXECUTE FUNCTION marcar_actualizado_en();

CREATE TRIGGER "UNIDADES_TIPOS_ACTUALIZADO_TRG"
  BEFORE UPDATE ON "UNIDADES_TIPOS"
  FOR EACH ROW
  EXECUTE FUNCTION marcar_actualizado_en();

CREATE TRIGGER "UNIDADES_ACTUALIZADO_TRG"
  BEFORE UPDATE ON "UNIDADES"
  FOR EACH ROW
  EXECUTE FUNCTION marcar_actualizado_en();

CREATE TRIGGER "LOTES_TIPOS_ACTUALIZADO_TRG"
  BEFORE UPDATE ON "LOTES_TIPOS"
  FOR EACH ROW
  EXECUTE FUNCTION marcar_actualizado_en();

CREATE TRIGGER "LOTES_TIPOS_UNIDADES_ACTUALIZADO_TRG"
  BEFORE UPDATE ON "LOTES_TIPOS_UNIDADES"
  FOR EACH ROW
  EXECUTE FUNCTION marcar_actualizado_en();

CREATE TRIGGER "LOTES_ACTUALIZADO_TRG"
  BEFORE UPDATE ON "LOTES"
  FOR EACH ROW
  EXECUTE FUNCTION marcar_actualizado_en();

CREATE TRIGGER "LOTES_PRODUCTOS_ACTUALIZADO_TRG"
  BEFORE UPDATE ON "LOTES_PRODUCTOS"
  FOR EACH ROW
  EXECUTE FUNCTION marcar_actualizado_en();

CREATE TRIGGER "UNIDADES_TRANSPORTE_ACTUALIZADO_TRG"
  BEFORE UPDATE ON "UNIDADES_TRANSPORTE"
  FOR EACH ROW
  EXECUTE FUNCTION marcar_actualizado_en();

CREATE TRIGGER "EXPEDICIONES_ACTUALIZADO_TRG"
  BEFORE UPDATE ON "EXPEDICIONES"
  FOR EACH ROW
  EXECUTE FUNCTION marcar_actualizado_en();

CREATE TRIGGER "EXPEDICIONES_LOTES_ACTUALIZADO_TRG"
  BEFORE UPDATE ON "EXPEDICIONES_LOTES"
  FOR EACH ROW
  EXECUTE FUNCTION marcar_actualizado_en();

ALTER FUNCTION marcar_actualizado_en() OWNER TO packing;

COMMIT;
