CREATE OR REPLACE FUNCTION lotes_tipos_unidades_validar()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  es_final boolean;
BEGIN
  IF TG_OP <> 'DELETE' THEN
    SELECT "ES_FINAL" INTO es_final
    FROM "LOTES_TIPOS"
    WHERE "ID" = NEW."ID_TIPO";

    IF es_final IS NULL THEN
      RAISE EXCEPTION 'tipo de lote inexistente' USING ERRCODE = '23503';
    END IF;

    IF NOT es_final THEN
      RAISE EXCEPTION 'un tipo que no es final no mide producto' USING ERRCODE = '23514';
    END IF;
  END IF;

  IF TG_OP = 'DELETE' OR (
    TG_OP = 'UPDATE'
    AND (
      NEW."ID_TIPO" IS DISTINCT FROM OLD."ID_TIPO"
      OR NEW."ID_UNIDAD" IS DISTINCT FROM OLD."ID_UNIDAD"
    )
  ) THEN
    IF EXISTS (
      SELECT 1
      FROM "LOTES" AS lote
      JOIN "LOTES_PRODUCTOS" AS producto ON producto."ID_LOTE" = lote."ID"
      WHERE lote."ID_TIPO" = OLD."ID_TIPO"
        AND producto."ID_UNIDAD" = OLD."ID_UNIDAD"
    ) THEN
      RAISE EXCEPTION 'hay productos con una medida que el tipo ya no permite' USING ERRCODE = '23514';
    END IF;
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  RETURN NEW;
END;
$$;

